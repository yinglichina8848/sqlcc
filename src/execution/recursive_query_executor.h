/**
 * WHY: 为什么需要专门的递归查询执行器？
 *
 * 递归查询是关系数据库中最重要的特性之一，支持对层次结构数据和图数据的查询，
 * 传统方案存在诸多技术挑战：
 * - 递归逻辑复杂：需要处理递归终止条件、循环检测、深度控制等
 * - 性能优化困难：递归查询容易造成性能问题和资源浪费
 * - 内存使用不控：递归深度过大时容易造成栈溢出和内存溢出
 * - 循环检测缺失：无法有效检测和处理递归查询中的循环引用
 * - 并发执行复杂：递归查询的并发执行需要特殊的同步机制
 * - 结果集管理：递归查询结果的去重、排序、限制等处理复杂
 *
 * 递归查询执行器的核心价值：
 * 1. 递归逻辑统一化：为所有递归查询提供统一的执行框架和接口
 * 2. 性能优化策略：针对不同递归模式实现专门的优化算法
 * 3. 内存安全管理：防止递归深度过大造成的栈溢出和内存问题
 * 4. 循环检测保护：有效检测和处理递归查询中的循环引用
 * 5. 并发安全执行：支持递归查询在多线程环境的安全执行
 * 6. 结果集智能管理：递归结果的去重、排序、限制等优化处理
 *
 * 🏗️ 设计模式：状态机模式(State Machine Pattern) + 策略模式(Strategy Pattern) + 迭代器模式(Iterator Pattern)
 *
 * 递归查询执行器作为状态机模式的应用：
 * - 状态转换：递归查询执行过程的状态转换和控制
 * - 状态验证：每个状态的执行条件和结果验证
 * - 状态恢复：执行失败时的状态回滚和恢复
 * - 状态监控：递归执行过程的状态监控和诊断
 *
 * SOLID原则体现：
 * - 单一职责：递归查询执行器专门负责递归查询的执行和管理
 * - 开闭原则：新递归算法通过扩展现有类实现
 * - 里氏替换：不同递归实现可以互相替换
 * - 接口隔离：递归查询接口精确定义执行契约
 * - 依赖倒置：执行器依赖抽象的查询接口而非具体实现
 *
 * WHAT: 递归查询执行器系统 - SQL递归查询统一执行框架
 *
 * 核心功能：
 * - 递归查询执行：执行WITH RECURSIVE子句的递归查询
 * - 递归策略选择：支持广度优先和深度优先两种递归策略
 * - 循环检测保护：有效检测和处理递归查询中的循环引用
 * - 递归深度控制：防止递归深度过大造成的性能问题
 * - 结果集去重：递归查询结果的自动去重和合并
 * - 性能监控统计：递归执行过程的性能监控和统计
 *
 * 系统组件：
 * - RecursiveQueryExecutor：核心执行器，协调整个递归查询过程
 * - BreadthFirstStrategy：广度优先递归策略实现
 * - DepthFirstStrategy：深度优先递归策略实现
 * - CycleDetector：循环检测器，检测递归过程中的循环引用
 * - DepthController：深度控制器，控制递归的最大深度
 * - ResultMerger：结果合并器，合并递归查询的中间结果
 *
 * 递归查询类型：
 * - 层次结构查询：组织架构、产品分类等层次结构数据查询
 * - 图遍历查询：社交网络、依赖关系等图结构数据遍历
 * - 路径查找查询：最短路径、最长路径等路径查找问题
 * - 递归聚合查询：递归计算的聚合函数查询
 * - 自定义递归查询：用户定义的复杂递归逻辑
 *
 * 递归策略：
 * - 广度优先：按层级顺序执行，适合查找最短路径
 * - 深度优先：沿一条路径执行到底，适合遍历完整结构
 * - 混合策略：根据查询特点动态选择最优策略
 * - 并行递归：多线程并行执行递归分支
 * - 自适应策略：根据执行情况动态调整递归策略
 *
 * 执行流程：
 * - 解析递归查询：解析WITH RECURSIVE子句的语法结构
 * - 初始化工作表：创建递归查询的工作表和初始状态
 * - 执行基础情况：执行递归查询的基础情况（非递归部分）
 * - 迭代递归执行：重复执行递归部分直到满足终止条件
 * - 循环检测检查：在每次迭代中检测可能的循环引用
 * - 结果集合并：将每次迭代的结果合并到最终结果集
 * - 终止条件判断：检查递归是否满足终止条件
 * - 最终结果返回：返回完整的递归查询结果
 *
 * 循环检测机制：
 * - 状态签名：为每个递归状态生成唯一签名
 * - 签名比较：比较当前状态与历史状态的签名
 * - 循环识别：识别循环引用并停止执行
 * - 循环报告：报告发现的循环信息和位置
 * - 循环恢复：提供循环检测后的恢复策略
 *
 * 性能优化策略：
 * - 记忆化存储：缓存已计算的递归结果避免重复计算
 * - 剪枝优化：根据条件提前终止无用递归分支
 * - 索引优化：利用索引加速递归查询的基础查询
 * - 并行执行：多线程并行执行独立的递归分支
 * - 批量处理：批量处理递归查询的中间结果
 *
 * 内存管理策略：
 * - 栈深度控制：限制递归调用的最大深度
 * - 结果集分页：大结果集的分页存储和处理
 * - 垃圾回收：及时清理不再需要的递归中间结果
 * - 内存监控：实时监控递归执行的内存使用情况
 * - 内存限制：设置递归查询的最大内存使用限制
 *
 * 并发控制机制：
 * - 线程安全：确保递归查询在多线程环境的安全执行
 * - 结果同步：多线程递归结果的同步和合并
 * - 资源隔离：不同递归查询间的资源隔离
 * - 死锁预防：避免递归查询产生的死锁情况
 * - 优先级调度：重要递归查询的优先级处理
 *
 * 接口设计：
 * - 执行接口：递归查询的主要执行接口
 * - 配置接口：递归查询参数和策略的配置接口
 * - 监控接口：递归查询执行性能和状态的监控接口
 * - 扩展接口：新递归算法和策略的扩展接口
 *
 * HOW: 递归查询执行器的实现机制
 *
 * 状态机模式实现：
 * 1. 状态定义：定义递归执行的不同状态（初始化、执行、终止等）
 * 2. 状态转换：根据执行结果进行状态间的转换
 * 3. 状态处理：每个状态的具体处理逻辑
 * 4. 状态验证：验证状态转换的合法性和条件
 * 5. 状态监控：监控状态转换过程和性能指标
 *
 * 递归策略实现：
 * 1. 策略接口：定义递归策略的通用接口
 * 2. 广度优先：使用队列实现层次遍历
 * 3. 深度优先：使用栈实现深度遍历
 * 4. 策略选择：根据查询特点选择最优策略
 * 5. 策略切换：在执行过程中动态切换策略
 *
 * 循环检测实现：
 * 1. 状态表示：将递归状态转换为可比较的形式
 * 2. 哈希计算：计算状态的哈希值用于快速比较
 * 3. 集合存储：存储已访问状态的集合
 * 4. 重复检测：检查当前状态是否已访问过
 * 5. 循环处理：发现循环时的处理策略
 *
 * 深度控制实现：
 * 1. 深度计数：记录当前递归的深度
 * 2. 深度限制：设置最大递归深度的限制
 * 3. 深度检查：在每次递归前检查深度限制
 * 4. 深度回溯：超出深度限制时的回溯处理
 * 5. 深度优化：根据数据特点动态调整深度限制
 *
 * 结果合并实现：
 * 1. 结果去重：消除递归结果中的重复行
 * 2. 结果排序：根据ORDER BY子句对结果排序
 * 3. 结果限制：应用LIMIT子句限制结果数量
 * 4. 结果分页：大结果集的分页处理
 * 5. 结果缓存：缓存中间结果以提高性能
 *
 * 内存优化实现：
 * 1. 迭代式执行：使用迭代替代递归调用
 * 2. 延迟求值：延迟计算不必要的递归分支
 * 3. 结果流式：流式处理递归结果避免大内存占用
 * 4. 对象复用：复用递归过程中的临时对象
 * 5. 内存池：使用内存池优化内存分配
 *
 * 并发优化实现：
 * 1. 任务分解：将递归查询分解为独立任务
 * 2. 线程池：利用线程池执行并发任务
 * 3. 结果同步：同步多线程的执行结果
 * 4. 负载均衡：平衡各线程的递归计算负载
 * 5. 资源协调：协调多线程间的资源使用
 *
 * 错误处理实现：
 * 1. 递归深度错误：超出最大递归深度的错误
 * 2. 循环检测错误：发现循环引用的错误
 * 3. 内存不足错误：递归执行内存不足的错误
 * 4. 超时错误：递归执行超时的错误
 * 5. 数据错误：递归查询中的数据错误的错误
 *
 * 扩展性设计：
 * - 插件架构：支持第三方递归算法的动态加载
 * - 自定义策略：用户自定义的递归执行策略
 * - 多语言支持：不同编程语言实现的递归逻辑
 * - 分布式扩展：支持分布式环境下的递归查询
 * - AI优化：基于机器学习的递归优化
 *
 * 调试和诊断：
 * - 执行跟踪：详细记录递归执行的每一步过程
 * - 状态监控：监控递归执行的状态转换和性能
 * - 循环分析：分析递归查询中的循环引用情况
 * - 性能分析：分析递归执行的性能瓶颈和优化机会
 * - 可视化工具：递归执行过程和结果的可视化展示
 */

#include "sql_parser/ast_nodes.h"
#pragma once

#include <memory>
#include <vector>
#include <string>
#include "sql_parser/recursive_query.h"
#include "src/core/core_database_manager.h"
#include "src/core/execution_context.h"
#include "src/core/execution_result.h"

namespace sqlcc {

class RecursiveQueryExecutor {
public:
    explicit RecursiveQueryExecutor(std::shared_ptr<DatabaseManager> db_manager);
    ~RecursiveQueryExecutor();

    // 执行递归查询
    ExecutionResult execute(const sql_parser::WithRecursiveClause& stmt, ExecutionContext& context);

    // 广度优先执行
    ExecutionResult executeBreadthFirst(const sql_parser::WithRecursiveClause& stmt, ExecutionContext& context);

    // 深度优先执行
    ExecutionResult executeDepthFirst(const sql_parser::WithRecursiveClause& stmt, ExecutionContext& context);

private:
    std::shared_ptr<DatabaseManager> db_manager_;

    // 递归上下文
    struct RecursiveContext {
        std::vector<Row> working_table;     // 当前迭代的工作表
        std::vector<Row> final_result;      // 最终结果集
        size_t max_iterations = 1000;       // 最大迭代次数
        size_t current_iteration = 0;       // 当前迭代次数
    };

    // 执行基础情况
    ExecutionResult executeBaseCase(const sql_parser::SelectStatement& base_query, ExecutionContext& context);

    // 执行递归情况
    ExecutionResult executeRecursiveCase(const sql_parser::SelectStatement& recursive_query,
                                       RecursiveContext& recursive_ctx,
                                       ExecutionContext& context);

    // 合并新行到结果集
    bool mergeNewRows(RecursiveContext& recursive_ctx, const std::vector<Row>& new_rows);

    // 循环检测
    bool detectCycle(const RecursiveContext& recursive_ctx) const;
};

} // namespace sqlcc
