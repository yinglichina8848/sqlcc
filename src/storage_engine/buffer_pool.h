#ifndef SQLCC_STORAGE_BUFFER_POOL_H
#define SQLCC_STORAGE_BUFFER_POOL_H

/**
 * WHY: 为什么需要缓冲池别名头文件？
 *
 * 数据库系统在重构过程中可能需要保持向后兼容性：
 * - 旧版本代码可能引用旧的头文件名
 * - 渐进式重构需要保持API兼容性
 * - 避免大规模代码修改导致的编译错误
 * - 分阶段迁移支持平滑过渡
 * - 减少重构风险和影响范围
 *
 * 缓冲池作为数据库系统的核心组件，其别名设计具有重要意义：
 * - 缓冲池是数据库性能的关键：缓存热点数据，减少磁盘I/O
 * - 分片缓冲池是性能优化：通过分片减少锁竞争，提高并发性能
 * - 向后兼容性保证：现有代码无需修改即可使用新实现
 * - 平滑迁移支持：允许分阶段替换缓冲池实现
 * - 零成本抽象：别名不引入额外的运行时开销
 *
 * WHAT: BufferPool - 缓冲池管理器别名头文件
 *
 * 为缓冲池分片实现提供向后兼容的别名接口：
 * - 别名机制：为buffer_pool_sharded.h提供兼容性别名
 * - 完全兼容：保持与原有buffer_pool接口的完全一致性
 * - 透明迁移：客户端代码无需感知底层的实现变化
 * - 性能保证：保持原有性能特征和行为语义
 * - 扩展支持：为未来缓冲池优化预留扩展空间
 *
 * 核心特性：
 * - 零开销抽象：编译时解析，无运行时性能损失
 * - 类型安全：完全保持原有类型的安全性和约束
 * - 接口一致性：保证所有方法的签名和语义不变
 * - 文档同步：注释和文档与实际实现保持同步
 * - 维护简化：集中管理向后兼容性问题
 *
 * HOW: 别名实现机制和技术细节
 *
 * 1. 头文件包含策略：
 *    - 直接包含：#include "buffer_pool/buffer_pool_sharded.h"
 *    - 透明转发：所有类型和函数都通过包含转发
 *    - 作用域保持：保持原有命名空间和作用域结构
 *    - 宏定义保护：使用#ifndef/#define防止重复包含
 *
 * 2. 向后兼容性保证：
 *    - 符号兼容：保持所有导出符号的名称和签名
 *    - 行为一致：保证方法的行为语义完全一致
 *    - 异常兼容：保持异常抛出行为的一致性
 *    - 性能特征：保持性能特征和内存使用模式
 *
 * 3. 迁移策略支持：
 *    - 分阶段替换：允许逐步替换缓冲池实现
 *    - 回滚支持：如有问题可以快速回滚到旧实现
 *    - 测试验证：在迁移过程中保持测试覆盖率
 *    - 监控保障：通过监控确保迁移过程的稳定性
 *
 * 4. 性能优化考虑：
 *    - 编译时解析：别名在编译时完全解析，无运行时开销
 *    - 内联优化：编译器可以进行跨文件内联优化
 *    - 缓存友好：保持原有的缓存访问模式
 *    - 内存对齐：维持原有的内存对齐和访问模式
 *
 * 5. 维护和演进策略：
 *    - 文档同步：保持别名头文件与实际实现的文档同步
 *    - 废弃警告：在适当时候添加废弃警告
 *    - 迁移指南：提供从旧接口到新接口的迁移指南
 *    - 版本管理：通过版本控制管理兼容性变化
 *
 * 🏗️ 设计模式：适配器模式 + 桥接模式
 *
 * 适配器模式应用：
 * - BufferPool别名作为适配器，适配新旧接口之间的差异
 * - 接口转换：将旧的缓冲池接口适配到新的分片实现
 * - 透明代理：对客户端隐藏底层实现的变更
 * - 渐进迁移：支持分阶段的系统重构和优化
 *
 * 桥接模式应用：
 * - 别名头文件作为桥接，连接客户端代码和实际实现
 * - 抽象分离：将缓冲池的抽象接口与具体实现分离
 * - 实现切换：允许在运行时或编译时切换不同的实现
 * - 扩展支持：为新的缓冲池实现预留扩展空间
 *
 * SOLID原则体现：
 *
 * 1. 单一职责原则(SRP)：
 *    - 别名头文件只负责提供向后兼容性
 *    - 具体缓冲池逻辑由buffer_pool_sharded.h负责
 *    - 职责分离清晰，功能单一
 *
 * 2. 开闭原则(OCP)：
 *    - 别名头文件保持稳定，不因实现变化而改变
 *    - 新实现可以通过包含关系进行扩展
 *    - 对扩展开放，对修改关闭
 *
 * 3. 里氏替换原则(LSP)：
 *    - 别名提供的接口完全替代原有接口使用
 *    - 保证行为语义的一致性和正确性
 *    - 客户端代码可以透明地使用别名
 *
 * 4. 接口隔离原则(ISP)：
 *    - 别名只暴露客户端需要的缓冲池接口
 *    - 不强制依赖不需要的接口和方法
 *    - 保持接口的简洁性和专注性
 *
 * 5. 依赖倒置原则(DIP)：
 *    - 客户端代码依赖缓冲池抽象接口
 *    - 不依赖具体的缓冲池实现细节
 *    - 通过头文件包含进行依赖注入
 *
 * 缓冲池分片设计的价值：
 * - 并发性能提升：减少锁竞争，提高多线程访问性能
 * - 内存效率优化：更好的内存局部性和缓存利用
 * - 可扩展性增强：支持更大规模的缓冲池管理
 * - 维护性改善：模块化设计便于测试和维护
 */

// 为兼容性提供 buffer_pool.h 别名
#include "buffer_pool/buffer_pool_sharded.h"

#endif // SQLCC_STORAGE_BUFFER_POOL_H
