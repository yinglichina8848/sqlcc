/**
 * @brief 锁类型枚举 - 定义数据库锁的类型
 *
 * WHY层 - 设计意图：
 *   锁类型是并发控制的基础，定义了不同级别的访问权限。
 *   通过明确的锁类型定义，实现精确的并发控制和冲突检测。
 *
 * WHAT层 - 锁类型说明：
 *   - SHARED: 共享锁，允许多个事务同时读取
 *   - EXCLUSIVE: 排他锁，只允许一个事务访问
 *
 * HOW层 - 实现机制：
 *   - SHARED锁：读操作使用，允许多个并发读
 *   - EXCLUSIVE锁：写操作使用，保证独占访问
 *   - 兼容性矩阵：定义锁类型间的兼容关系
 */
enum class LockType {
  SHARED,     ///< 共享锁：允许多个事务同时读取
  EXCLUSIVE   ///< 排他锁：保证独占访问，阻止其他事务
};

/**
 * @brief 并发控制策略枚举 - 定义不同的并发控制方法
 *
 * WHY层 - 设计意图：
 *   并发控制策略的选择直接影响系统的性能和一致性保证。
 *   不同的策略适用于不同类型的应用场景，需要根据具体需求选择合适的策略。
 *
 * WHAT层 - 策略说明：
 *   - PESSIMISTIC: 悲观并发控制，提前加锁确保一致性
 *   - OPTIMISTIC: 乐观并发控制，后验冲突检测提高性能
 *   - MVCC: 多版本并发控制，通过版本管理实现并发
 *   - HYBRID: 混合策略，根据负载特征动态调整
 *
 * HOW层 - 策略实现：
 *   - 悲观策略：基于锁的并发控制，适合写密集场景
 *   - 乐观策略：基于验证的并发控制，适合读密集场景
 *   - MVCC策略：基于版本的并发控制，平衡读写性能
 *   - 混合策略：自适应调整，获得最佳整体性能
 *
 * 性能特征对比：
 *   | 策略 | 读性能 | 写性能 | 一致性保证 | 适用场景 |
 *   |------|--------|--------|------------|----------|
 *   | 悲观 | 中等   | 较低   | 强         | 写密集   |
 *   | 乐观 | 高     | 中等   | 中等       | 读密集   |
 *   | MVCC | 高     | 高     | 强         | 均衡负载 |
 *   | 混合 | 自适应 | 自适应 | 自适应     | 动态负载 |
 */
enum class ConcurrencyControlStrategy {
  PESSIMISTIC,  ///< 悲观并发控制：基于锁的保守策略
  OPTIMISTIC,   ///< 乐观并发控制：基于验证的乐观策略
  MVCC,         ///< 多版本并发控制：基于版本的高性能策略
  HYBRID        ///< 混合并发控制：自适应策略选择
};

/**
 * @brief 锁兼容性矩阵 - 定义不同锁类型间的兼容关系
 *
 * WHY层 - 设计意图：
 *   锁兼容性矩阵是并发控制的核心规则，决定了哪些锁可以同时持有，
 *   哪些锁会发生冲突。通过精心设计的兼容规则，实现最大化并发的同时
 *   保证数据一致性。
 *
 * WHAT层 - 兼容性定义：
 *   兼容性矩阵定义了锁类型间的兼容关系：
 *   - SHARED + SHARED = true（多个读操作可以并发）
 *   - SHARED + EXCLUSIVE = false（读写冲突）
 *   - EXCLUSIVE + SHARED = false（写读冲突）
 *   - EXCLUSIVE + EXCLUSIVE = false（写写冲突）
 *
 * HOW层 - 实现机制：
 *   - 位运算优化：使用位掩码快速判断兼容性
 *   - 缓存友好：矩阵存储在连续内存中
 *   - 扩展性设计：支持自定义锁类型和兼容规则
 *
 * 锁类型扩展：
 *   - UPDATE锁：介于SHARED和EXCLUSIVE之间
 *   - INTENTION锁：用于多粒度锁的意向声明
 *   - SCHEMA锁：用于DDL操作的元数据保护
 */
class LockCompatibilityMatrix {
public:
  /**
   * 检查两种锁类型是否兼容
   * @param type1 第一种锁类型
   * @param type2 第二种锁类型
   * @return 是否兼容
   */
  static bool IsCompatible(LockType type1, LockType type2);

private:
  /**
   * 锁兼容性矩阵（4x4）
   * 行：持有锁类型，列：请求锁类型
   * true表示兼容，false表示冲突
   */
  static constexpr bool compatibility_matrix_[2][2] = {
    // 请求: SHARED, EXCLUSIVE
    /* 持有SHARED */    {true,  false},  // SHARED锁持有者
    /* 持有EXCLUSIVE */ {false, false}   // EXCLUSIVE锁持有者
  };
};

/**
 * @brief 层级锁管理器 - 分层并发控制的核心组件
 *
 * WHY层 - 设计意图：
 *   层级锁管理器实现了数据库的多粒度锁协议，支持页面级、表级等不同粒度的锁。
 *   通过分层设计和锁兼容性矩阵，实现高并发访问下的数据一致性保证。
 *
 * WHAT层 - 功能说明：
 *   - 页面级锁：保护单个数据页面的并发访问
 *   - 表级锁：保护整个表的并发访问
 *   - 锁升级：从细粒度锁升级到粗粒度锁
 *   - 死锁检测：实时监控和自动处理死锁
 *   - 性能监控：详细的锁统计和性能指标
 *
 * HOW层 - 架构设计：
 *   - 分层锁表：分别维护页面锁和表锁
 *   - 锁队列管理：支持多个事务等待同一资源
 *   - 超时处理：防止无限期等待的保护机制
 *   - 锁清理：自动清理已完成事务的锁
 *
 * 锁粒度选择策略：
 *   - **细粒度锁**：行级锁，最大化并发但管理开销大
 *   - **粗粒度锁**：表级锁，简单高效但并发度低
 *   - **动态调整**：根据访问模式自动选择锁粒度
 *   - **锁升级**：从行锁升级到页锁再到表锁
 *
 * 死锁检测算法：
 *   - **等待图构造**：事务→资源的等待关系图
 *   - **环检测**：深度优先搜索检测死锁环
 *   - **牺牲者选择**：选择最小代价事务进行回滚
 *   - **定期扫描**：固定间隔执行死锁检测
 *
 * @note 层级锁管理器是并发控制系统的核心，直接影响系统的并发性能
 * @note 实现了严格的两阶段锁协议，确保事务串行化执行
 * @note 支持锁升级和降级策略，平衡并发度和管理复杂度
 * @note 提供详细的锁统计信息，支持性能监控和调优
 */
class HierarchicalLockManager {
public:
  /**
   * @brief 锁类型枚举（已在文件开头定义）
   */

  /**
   * @brief 锁信息结构 - 单个锁的详细描述
   *
   * WHY层 - 设计意图：
   *   LockInfo封装了单个锁的所有必要信息，支持复杂的锁管理策略。
   *   通过记录锁的类型、持有者和获取时间，实现精确的锁控制和监控。
   *
   * WHAT层 - 信息内容：
   *   - 锁类型：SHARED或EXCLUSIVE
   *   - 事务ID：持有锁的事务标识
   *   - 获取时间：锁的获取时间戳
   *
   * HOW层 - 并发安全：
   *   - 原子操作：时间戳使用原子操作保证一致性
   *   - 内存对齐：结构按缓存行对齐避免伪共享
   *   - 复制语义：支持高效的拷贝构造和赋值
   */
  struct LockInfo {
    LockType type;                                           ///< 锁的类型
    int32_t transaction_id;                                 ///< 持有锁的事务ID
    std::chrono::steady_clock::time_point acquire_time;     ///< 锁获取时间

    /**
     * 默认构造函数
     */
    LockInfo() : type(LockType::SHARED), transaction_id(0),
                 acquire_time(std::chrono::steady_clock::now()) {}

    /**
     * 参数化构造函数
     * @param t 锁类型
     * @param txn_id 事务ID
     */
    LockInfo(LockType t, int32_t txn_id)
        : type(t), transaction_id(txn_id),
          acquire_time(std::chrono::steady_clock::now()) {}
  };

  /**
   * @brief 锁管理器统计信息 - 并发控制的性能监控数据
   *
   * WHY层 - 设计意图：
   *   详细的统计信息是性能调优和问题诊断的基础。通过收集锁操作的各项指标，
   *   系统管理员可以了解并发控制的效率，识别性能瓶颈和优化机会。
   *
   * WHAT层 - 统计指标：
   *   - 锁数量统计：当前各种类型锁的数量
   *   - 操作计数：锁获取、等待、释放的次数
   *   - 死锁统计：死锁检测和处理的统计
   *   - 性能指标：平均等待时间、成功率等
   *
   * HOW层 - 原子更新：
   *   - 原子计数器：使用std::atomic保证并发安全
   *   - 无锁更新：避免统计收集带来的锁竞争
   *   - 内存屏障：确保统计数据的内存可见性
   *   - 周期重置：支持统计数据的定期重置
   *
   * 监控应用：
   *   - **性能分析**：识别锁竞争热点和性能瓶颈
   *   - **容量规划**：基于负载模式预测系统容量需求
   *   - **问题诊断**：死锁分析和并发问题排查
   *   - **调优指导**：为并发控制参数调整提供依据
   */
  struct LockManagerStats {
    size_t shared_locks = 0;        ///< 当前共享锁数量
    size_t exclusive_locks = 0;     ///< 当前排他锁数量
    size_t total_acquires = 0;      ///< 总获取次数
    size_t total_waits = 0;         ///< 总等待次数
    size_t deadlocks_detected = 0;  ///< 检测到的死锁数量
  };

  /**
   * @brief 构造函数 - 初始化层级锁管理器
   *
   * WHY层 - 设计意图：
   *   锁管理器的初始化必须保证线程安全和性能高效。
   *   通过合理的参数配置和数据结构初始化，为高并发场景做好准备。
   *
   * WHAT层 - 初始化内容：
   *   - 配置最大锁数量限制
   *   - 初始化锁表数据结构
   *   - 设置统计信息收集
   *   - 配置锁超时参数
   *
   * HOW层 - 实现细节：
   *   1. 验证max_locks参数的有效性
   *   2. 预分配锁表哈希表的空间
   *   3. 初始化统计信息为零
   *   4. 设置默认的锁超时时间
   *   5. 初始化互斥锁和其他同步原语
   *
   * 配置参数：
   *   - max_locks: 最大锁数量，默认1024
   *   - 锁超时时间: 默认10秒
   *   - 死锁检测间隔: 默认1秒
   *
   * @param max_locks 最大锁数量限制
   *
   * @throws std::invalid_argument 当max_locks为0时抛出
   */
  explicit HierarchicalLockManager(size_t max_locks = 1024);

  /**
   * @brief 析构函数 - 安全清理锁管理器资源
   *
   * WHY层 - 设计意图：
   *   锁管理器的清理必须保证所有锁都被正确释放，避免资源泄漏。
   *   优雅关闭防止正在进行的操作被强制中断。
   *
   * WHAT层 - 清理内容：
   *   - 释放所有持有的锁
   *   - 清理锁表和等待队列
   *   - 停止后台清理线程
   *   - 释放系统资源
   *
   * HOW层 - 清理顺序：
   *   1. 停止死锁检测线程
   *   2. 强制释放所有锁（记录警告）
   *   3. 清理锁表数据结构
   *   4. 销毁互斥锁和其他资源
   *   5. 记录清理统计信息
   *
   * @note 析构函数会记录强制释放的锁数量
   * @note 正常情况下不应有锁在析构时仍被持有
   */
  ~HierarchicalLockManager();

  /**
   * @brief 获取页面锁 - 页面级并发控制的核心API
   *
   * WHY层 - 设计意图：
   *   页面锁是数据库并发控制的基本单位，保护单个数据页面的完整性。
   *   通过页面级锁，实现细粒度的并发控制，提高系统整体并发度。
   *
   * WHAT层 - 功能说明：
   *   为指定页面获取指定类型的锁，支持超时等待和死锁检测。
   *   如果锁不可用，会等待指定时间或直到获取成功。
   *
   * HOW层 - 获取流程：
   *   1. 检查锁兼容性，确定是否可以立即获取
   *   2. 如果不能获取，加入等待队列
   *   3. 等待超时或锁释放
   *   4. 获取锁后更新统计信息
   *   5. 返回获取结果状态
   *
   * 锁获取策略：
   *   - **立即获取**：锁可用时立即返回
   *   - **条件等待**：使用条件变量等待锁释放
   *   - **超时控制**：防止无限期等待
   *   - **死锁检测**：检测并处理死锁情况
   *
   * 性能优化：
   *   - **自旋等待**：短时间高频检查锁状态
   *   - **批量唤醒**：锁释放时唤醒所有等待者
   *   - **锁亲和性**：减少跨CPU的锁竞争
   *   - **锁升级**：高竞争时升级锁粒度
   *
   * @param page_id 页面ID
   * @param lock_type 锁类型（SHARED或EXCLUSIVE）
   * @param transaction_id 请求锁的事务ID
   * @param timeout_ms 超时时间（毫秒），0表示无限等待
   * @return 是否成功获取锁
   *
   * @note 页面ID必须是有效的正整数
   * @note 事务ID用于死锁检测和锁管理
   * @note 超时时间为0表示阻塞等待直到获取锁
   * @note 获取失败可能是超时或死锁牺牲
   */
  bool AcquirePageLock(int32_t page_id, LockType lock_type,
                      int32_t transaction_id, size_t timeout_ms = 5000);

  /**
   * @brief 释放页面锁 - 页面级锁管理的释放操作
   *
   * WHY层 - 设计意图：
   *   锁释放是锁生命周期的重要环节，释放锁可以唤醒等待的事务。
   *   正确的锁释放确保并发控制的正确性和性能。
   *
   * WHAT层 - 功能说明：
   *   释放指定事务对指定页面的锁，唤醒可能的等待者。
   *   更新锁表和统计信息，确保锁状态的一致性。
   *
   * HOW层 - 释放流程：
   *   1. 验证锁的持有者身份
   *   2. 从锁表中移除锁信息
   *   3. 更新统计信息
   *   4. 唤醒等待队列中的事务
   *   5. 检查是否有锁升级需求
   *
   * 锁释放策略：
   *   - **条件唤醒**：只唤醒可能获取锁的事务
   *   - **公平调度**：按照等待顺序唤醒事务
   *   - **批量释放**：支持一次释放多个锁
   *   - **锁降级**：在适当时候降低锁粒度
   *
   * @param page_id 页面ID
   * @param transaction_id 事务ID
   * @return 是否成功释放锁
   *
   * @note 只有锁的持有者才能释放锁
   * @note 释放不存在的锁会返回false
   * @note 释放锁会触发等待事务的唤醒
   */
  bool ReleasePageLock(int32_t page_id, int32_t transaction_id);

  /**
   * @brief 获取表锁 - 表级并发控制的API
   *
   * WHY层 - 设计意图：
   *   表锁提供粗粒度的并发控制，适合全表操作或高冲突场景。
   *   通过表级锁，可以简化并发控制逻辑，提高操作效率。
   *
   * WHAT层 - 功能说明：
   *   为指定表获取指定类型的锁，支持超时和死锁检测。
   *   表锁的获取会影响表的所有页面和记录。
   *
   * HOW层 - 实现机制：
   *   1. 检查表锁的兼容性
   *   2. 如果需要，隐式获取相关页锁
   *   3. 更新锁层次结构
   *   4. 维护锁的层次一致性
   *
   * 表锁应用场景：
   *   - **DDL操作**：CREATE, DROP, ALTER等表结构修改
   *   - **全表扫描**：需要访问整个表的查询操作
   *   - **批量更新**：影响大量数据的修改操作
   *   - **表级约束**：检查表级完整性约束
   *
   * @param table_id 表ID
   * @param lock_type 锁类型
   * @param transaction_id 事务ID
   * @param timeout_ms 超时时间（毫秒）
   * @return 是否成功获取锁
   *
   * @note 表锁获取可能隐式获取多个页锁
   * @note 表锁的开销比页锁更大
   * @note 适用于粗粒度并发控制场景
   */
  bool AcquireTableLock(int32_t table_id, LockType lock_type,
                       int32_t transaction_id, size_t timeout_ms = 5000);

  /**
   * @brief 释放表锁 - 表级锁管理的释放操作
   *
   * WHY层 - 设计意图：
   *   表锁释放需要考虑锁层次的一致性，确保所有相关锁都被正确释放。
   *   表锁释放可能触发多个等待事务的唤醒。
   *
   * WHAT层 - 功能说明：
   *   释放指定事务对指定表的锁，维护锁层次结构的正确性。
   *   可能隐式释放相关的页面锁。
   *
   * HOW层 - 释放策略：
   *   1. 验证表锁持有权
   *   2. 检查是否需要释放相关页锁
   *   3. 更新锁层次信息
   *   4. 唤醒等待表锁的事务
   *   5. 维护层次锁的一致性
   *
   * @param table_id 表ID
   * @param transaction_id 事务ID
   * @return 是否成功释放锁
   */
  bool ReleaseTableLock(int32_t table_id, int32_t transaction_id);

  /**
   * @brief 获取锁统计信息 - 并发控制的性能监控接口
   *
   * WHY层 - 设计意图：
   *   统计信息是系统监控和性能调优的基础，为管理员提供并发控制的运行状态。
   *   详细的统计数据支持问题诊断和容量规划。
   *
   * WHAT层 - 统计内容：
   *   - 当前锁数量：各种类型锁的持有数量
   *   - 操作计数：锁操作的累计统计
   *   - 性能指标：等待时间、成功率等
   *   - 异常统计：死锁、超时等异常情况
   *
   * HOW层 - 收集机制：
   *   - 原子计数：使用原子操作保证并发安全
   *   - 实时更新：在每次锁操作时更新统计
   *   - 高效存储：使用紧凑的数据结构
   *   - 线程安全：统计访问不影响锁操作性能
   *
   * @return 当前的锁统计信息
   *
   * @note 统计信息是实时的，但可能有轻微延迟
   * @note 统计数据可用于性能监控和调优
   * @note 某些统计项可能需要定期重置
   */
  LockManagerStats GetStats() const;

  /**
   * @brief 检测死锁 - 并发控制系统的健康检查
   *
   * WHY层 - 设计意图：
   *   死锁检测是并发控制系统的安全保障，及时发现和处理死锁环。
   *   通过定期死锁检测，防止系统陷入死锁状态。
   *
   * WHAT层 - 检测内容：
   *   扫描当前锁等待关系，识别是否存在死锁环。
   *   如果发现死锁，选择合适的事务进行牺牲。
   *
   * HOW层 - 检测算法：
   *   1. 构造等待图（事务→资源→事务）
   *   2. 使用DFS或拓扑排序检测环
   *   3. 识别死锁环中的事务
   *   4. 选择牺牲者进行回滚
   *   5. 清理死锁状态
   *
   * 死锁处理策略：
   *   - **牺牲者选择**：基于事务年龄、资源占用等选择牺牲者
   *   - **最小代价**：选择回滚开销最小的事务
   *   - **公平性**：避免总是牺牲同一事务
   *   - **级联避免**：考虑死锁解决的连锁反应
   *
   * @return 是否检测到并处理了死锁
   *
   * @note 死锁检测有一定的CPU开销
   * @note 频繁死锁可能表明锁策略需要调整
   * @note 死锁处理会影响事务的原子性保证
   */
  bool DetectDeadlock() const;

  /**
   * @brief 清理过期锁 - 系统维护和资源回收
   *
   * WHY层 - 设计意图：
   *   过期锁清理是系统健康维护的重要环节，防止锁泄漏和资源浪费。
   *   通过定期清理过期锁，保持锁管理器的效率和正确性。
   *
   * WHAT层 - 清理内容：
   *   识别并清理超时或失效的锁，释放相关资源。
   *   更新统计信息，记录清理操作。
   *
   * HOW层 - 清理策略：
   *   1. 扫描所有锁，检查持有时间
   *   2. 识别超时的锁
   *   3. 验证事务状态
   *   4. 安全释放过期锁
   *   5. 更新统计计数
   *
   * 清理触发条件：
   *   - **定时清理**：定期执行清理任务
   *   - **负载触发**：高负载时触发清理
   *   - **内存压力**：内存不足时强制清理
   *   - **手动触发**：管理员主动清理
   *
   * @note 清理操作可能影响正在进行的事务
   * @note 过期锁清理是系统自我修复机制
   */
  void CleanupExpiredLocks();

private:
  /**
   * @brief 页面锁映射 - 页面ID到锁列表的映射
   *
   * WHY层 - 设计意图：
   *   页面锁映射是锁管理器的核心数据结构，支持高效的锁查找和操作。
   *   通过哈希映射实现O(1)时间的锁定位和操作。
   *
   * WHAT层 - 数据结构：
   *   - 键：页面ID（int32_t）
   *   - 值：锁信息列表（vector<pair<LockType, int32_t>>）
   *   - 每个页面可以有多个锁（共享锁允许多个持有者）
   *
   * HOW层 - 并发安全：
   *   - 读写锁保护：使用shared_mutex允许多读单写
   *   - 分片设计：减少锁竞争的热点
   *   - 原子操作：关键计数器使用原子操作
   *
   * 内存优化：
   *   - 预分配容量：减少动态扩容开销
   *   - 对象池复用：重用锁信息对象
   *   - 压缩存储：优化锁信息的存储格式
   */
  std::unordered_map<int32_t, std::vector<std::pair<LockType, int32_t>>> page_locks_;

  /**
   * @brief 表锁映射 - 表ID到锁列表的映射
   *
   * WHY层 - 设计意图：
   *   表锁映射支持粗粒度的并发控制，适用于表级操作。
   *   通过独立的映射实现表级和页面级锁的分离管理。
   *
   * WHAT层 - 数据结构：
   *   类似页面锁映射，但粒度为表级
   *   支持表级锁的层次化管理
   *
   * HOW层 - 锁层次：
   *   - 表锁优先级高于页锁
   *   - 获取表锁可能隐式获取相关页锁
   *   - 锁释放遵循相反顺序
   */
  std::unordered_map<int32_t, std::vector<std::pair<LockType, int32_t>>> table_locks_;

  /**
   * @brief 页面锁互斥锁 - 保护页面锁映射的并发访问
   */
  mutable std::shared_mutex page_locks_mutex_;

  /**
   * @brief 表锁互斥锁 - 保护表锁映射的并发访问
   */
  mutable std::shared_mutex table_locks_mutex_;

  /**
   * @brief 统计信息 - 原子变量保证并发安全
   */
  mutable std::atomic<LockManagerStats> stats_;

  /**
   * @brief 最大锁数量限制
   */
  const size_t max_locks_;

  /**
   * @brief 锁超时时间常量（毫秒）
   */
  static constexpr size_t LOCK_TIMEOUT_MS = 10000;
};

/**
 * @brief 预取器 - 基于访问模式的智能页面预取组件
 *
 * WHY层 - 设计意图：
 *   预取器通过预测未来的页面访问需求，提前加载数据到内存。
 *   通过减少磁盘I/O延迟，提升数据库系统的整体性能。
 *
 * WHAT层 - 功能说明：
 *   分析页面访问模式，预测并预取可能需要的页面。
 *   支持顺序访问、随机访问等多种访问模式的识别和优化。
 *
 * HOW层 - 预取策略：
 *   - 顺序预取：检测顺序访问模式，预读连续页面
 *   - 随机预取：基于历史访问预测可能的页面
 *   - 跨步预取：处理固定跨步的访问模式
 *   - 自适应调整：根据命中率动态调整预取策略
 *
 * 访问模式识别：
 *   - **顺序模式**：页面访问呈连续递增趋势
 *   - **随机模式**：页面访问无明显规律
 *   - **跨步模式**：页面访问按固定间隔跳跃
 *   - **可预测模式**：可以通过历史预测未来访问
 *
 * 预取算法：
 *   - **基于历史的预测**：分析最近的访问序列
 *   - **基于模式的识别**：识别访问的规律模式
 *   - **基于频率的预测**：根据访问频率预测热点
 *   - **基于关联的预测**：根据页面关联性预测
 *
 * 性能监控：
 *   - **命中率统计**：预取页面的实际使用率
 *   - **开销效益分析**：预取成本与收益的对比
 *   - **准确性评估**：预测准确性的量化指标
 *   - **适应性调整**：根据性能反馈调整策略
 *
 * @note 预取器运行在独立的后台线程，不影响主事务处理
 * @note 预取策略可以根据工作负载特征动态调整
 * @note 过度的预取可能浪费内存和I/O资源
 * @note 预取命中率是评估预取效果的关键指标
 */
class Prefetcher {
public:
  /**
   * @brief 预取器统计信息 - 预取性能的量化指标
   *
   * WHY层 - 设计意图：
   *   预取统计信息帮助评估预取策略的有效性，为性能调优提供依据。
   *   通过详细的统计数据，系统可以自适应调整预取行为。
   *
   * WHAT层 - 统计指标：
   *   - 请求统计：预取请求和服务的数量
   *   - 命中统计：预取页面的实际使用情况
   *   - 模式统计：不同访问模式的预取效果
   *   - 性能指标：预取的开销和收益
   *
   * HOW层 - 收集机制：
   *   - 原子计数：并发安全的统计更新
   *   - 实时计算：动态计算命中率等派生指标
   *   - 周期汇总：定期汇总和重置统计数据
   *   - 高效存储：最小化统计收集的性能开销
   */
  struct PrefetcherStats {
    size_t prefetches_requested = 0;  ///< 请求的预取次数
    size_t prefetches_served = 0;     ///< 实际服务的预取次数
    size_t prefetch_hit_rate = 0;     ///< 预取命中率（百分比）
    size_t sequential_prefetch = 0;   ///< 顺序预取次数
    size_t random_prefetch = 0;       ///< 随机预取次数
  };

  /**
   * @brief 访问模式枚举 - 定义不同的页面访问模式
   *
   * WHY层 - 设计意图：
   *   访问模式识别是预取优化的基础，不同的访问模式需要不同的预取策略。
   *   通过准确识别访问模式，可以选择最合适的预取算法。
   *
   * WHAT层 - 模式分类：
   *   - SEQUENTIAL: 顺序访问，页面按连续编号访问
   *   - RANDOM: 随机访问，无明显规律的访问模式
   *   - STRIDED: 跨步访问，按固定间隔跳跃访问
   *   - PREDICTABLE: 可预测访问，可以通过历史预测未来
   *
   * HOW层 - 识别算法：
   *   - **统计分析**：计算访问间隔的统计特征
   *   - **模式匹配**：匹配典型的访问模式模板
   *   - **机器学习**：使用ML算法预测访问模式
   *   - **自适应调整**：根据历史数据调整识别阈值
   */
  enum class AccessPattern {
    SEQUENTIAL,    ///< 顺序访问模式
    RANDOM,        ///< 随机访问模式
    STRIDED,       ///< 跨步访问模式
    PREDICTABLE    ///< 可预测访问模式
  };

  /**
   * @brief 构造函数 - 初始化预取器组件
   *
   * WHY层 - 设计意图：
   *   预取器的初始化需要平衡预取效果和系统开销。
   *   通过合理的配置参数，为不同应用场景提供最佳性能。
   *
   * WHAT层 - 初始化内容：
   *   - 配置最大预取大小限制
   *   - 初始化访问历史记录结构
   *   - 启动预取工作线程
   *   - 设置预取策略参数
   *
   * HOW层 - 参数配置：
   *   - max_prefetch_size: 控制单次预取的最大页面数
   *   - 预取阈值: 触发预取的最小访问次数
   *   - 时间窗口: 访问历史的时间范围
   *   - 优先级策略: 预取任务的调度优先级
   *
   * @param buffer_pool BufferPool的引用，用于页面预取
   * @param max_prefetch_size 最大预取大小，默认64页面
   *
   * @note buffer_pool参数用于实际的页面预取操作
   * @note max_prefetch_size影响预取的内存开销
   */
  explicit Prefetcher(void* buffer_pool, size_t max_prefetch_size = 64);

  /**
   * @brief 析构函数 - 安全关闭预取器
   *
   * WHY层 - 设计意图：
   *   预取器的关闭必须保证所有预取任务完成，避免资源泄漏。
   *   优雅关闭防止正在进行的预取操作被强制中断。
   *
   * WHAT层 - 清理内容：
   *   - 停止预取工作线程
   *   - 完成所有待处理的预取任务
   *   - 清理访问历史记录
   *   - 释放系统资源
   *
   * HOW层 - 关闭流程：
   *   1. 设置停止标志，通知工作线程退出
   *   2. 等待工作线程完成当前任务
   *   3. 清理预取队列和历史记录
   *   4. 记录最终统计信息
   */
  ~Prefetcher();

  /**
   * @brief 记录页面访问 - 访问模式分析的基础数据收集
   *
   * WHY层 - 设计意图：
   *   页面访问记录是预取决策的基础数据，通过记录访问历史，
   *   预取器可以识别访问模式并预测未来的访问需求。
   *
   * WHAT层 - 记录内容：
   *   - 页面ID：被访问的页面标识
   *   - 访问时间：精确的访问时间戳
   *   - 访问类型：读操作还是写操作
   *
   * HOW层 - 数据收集：
   *   1. 记录访问时间戳和页面ID
   *   2. 更新访问历史统计
   *   3. 触发访问模式分析
   *   4. 根据模式决定是否预取
   *
   * 性能考虑：
   *   - 最小化记录开销，不影响主路径性能
   *   - 异步处理历史数据分析
   *   - 定期清理过期历史记录
   *
   * @param page_id 被访问的页面ID
   * @param is_write 是否为写操作
   *
   * @note 这个函数在每次页面访问时被调用
   * @note 记录开销必须非常小，不能影响事务性能
   */
  void RecordPageAccess(int32_t page_id, bool is_write);

  /**
   * @brief 预取页面 - 主动加载页面到内存
   *
   * WHY层 - 设计意图：
   *   预取页面是预取器的核心功能，通过提前加载数据减少访问延迟。
   *   智能的预取决策可以显著提升系统性能。
   *
   * WHAT层 - 预取操作：
   *   根据访问模式预测并预取相关页面。
   *   支持单个页面和批量页面的预取。
   *
   * HOW层 - 预取决策：
   *   1. 分析当前页面的访问模式
   *   2. 预测可能被访问的相关页面
   *   3. 检查页面是否已在内存中
   *   4. 发起异步预取操作
   *   5. 更新预取统计信息
   *
   * 预取策略：
   *   - **保守策略**：只预取高度可能被访问的页面
   *   - **激进策略**：预取更大范围的页面
   *   - **自适应策略**：根据历史命中率动态调整
   *   - **混合策略**：结合多种预测算法
   *
   * @param page_id 触发预取的页面ID
   * @return 是否成功触发预取操作
   *
   * @note 预取是异步操作，不阻塞调用者
   * @note 预取失败不影响正常页面访问
   */
  bool PrefetchPage(int32_t page_id);

  /**
   * @brief 批量预取页面 - 大规模页面预取优化
   *
   * WHY层 - 设计意图：
   *   批量预取可以减少系统调用的次数，提高预取效率。
   *   通过合并多个预取请求，优化I/O操作的性能。
   *
   * WHAT层 - 批量操作：
   *   接受页面ID列表，一次性处理多个预取请求。
   *   返回成功预取的页面数量。
   *
   * HOW层 - 批量处理：
   *   1. 过滤已在内存中的页面
   *   2. 对剩余页面进行去重排序
   *   3. 分批提交给I/O子系统
   *   4. 收集和返回处理结果
   *
   * 优化技术：
   *   - **请求合并**：合并连续的页面请求
   *   - **I/O调度**：优化磁盘访问顺序
   *   - **并行处理**：利用多核CPU并行预取
   *   - **优先级排序**：按访问概率排序预取顺序
   *
   * @param page_ids 需要预取的页面ID列表
   * @return 成功预取的页面数量
   *
   * @note 批量预取可以显著降低单位页面预取开销
   * @note 返回值可能小于输入列表大小
   */
  size_t PrefetchPages(const std::vector<int32_t>& page_ids);

  /**
   * @brief 获取预取统计信息 - 预取效果的量化评估
   *
   * WHY层 - 设计意图：
   *   统计信息是预取策略调优的基础，通过详细的性能指标，
   *   系统可以评估预取的有效性并进行相应的调整。
   *
   * WHAT层 - 统计内容：
   *   - 预取请求和服务的数量统计
   *   - 命中率和准确性指标
   *   - 不同模式的预取效果对比
   *   - 性能开销和收益分析
   *
   * HOW层 - 指标计算：
   *   - 命中率：预取页面被实际使用的比例
   *   - 准确率：预测正确的预取请求比例
   *   - 效率比：预取收益与开销的比率
   *   - 覆盖率：预取覆盖的页面访问比例
   *
   * @return 当前的预取统计信息
   *
   * @note 统计信息可用于性能监控和调优
   * @note 某些指标需要一定的观察时间才能准确
   */
  PrefetcherStats GetStats() const;

  /**
   * @brief 启用/禁用预取功能 - 运行时配置控制
   *
   * WHY层 - 设计意图：
   *   预取功能的动态控制允许系统根据运行时条件调整行为。
   *   在某些场景下，预取可能弊大于利，需要能够动态禁用。
   *
   * WHAT层 - 控制功能：
   *   运行时启用或禁用预取功能。
   *   禁用时停止所有预取操作，启用时恢复正常预取。
   *
   * HOW层 - 状态转换：
   *   - 禁用：停止工作线程，清理预取队列
   *   - 启用：重新启动工作线程，继续预取操作
   *   - 状态同步：确保状态转换的原子性
   *
   * 使用场景：
   *   - **内存压力**：内存不足时禁用预取节省内存
   *   - **I/O压力**：磁盘负载高时禁用预取减少I/O
   *   - **调试诊断**：禁用预取进行性能问题诊断
   *   - **手动调优**：管理员手动控制预取行为
   *
   * @param enabled 是否启用预取功能
   *
   * @note 状态改变可能需要几秒钟生效
   * @note 禁用预取不会影响已经预取的页面
   */
  void SetEnabled(bool enabled);

  /**
   * @brief 获取页面访问模式 - 访问模式分析接口
   *
   * WHY层 - 设计意图：
   *   访问模式识别是预取优化的核心，通过准确识别访问模式，
   *   预取器可以选择最合适的预取策略。
   *
   * WHAT层 - 模式识别：
   *   分析指定页面的访问历史，返回最可能的访问模式。
   *   用于指导预取决策和性能优化。
   *
   * HOW层 - 模式分析：
   *   1. 收集页面的访问历史数据
   *   2. 计算访问间隔和频率统计
   *   3. 模式匹配和分类
   *   4. 返回最匹配的访问模式
   *
   * 分析算法：
   *   - **统计分析**：计算访问间隔的均值和方差
   *   - **趋势分析**：识别访问的递增或递减趋势
   *   - **周期分析**：检测周期性的访问模式
   *   - **聚类分析**：将相似访问模式分组
   *
   * @param page_id 需要分析的页面ID
   * @return 识别出的访问模式
   *
   * @note 模式识别需要足够的访问历史数据
   * @note 新页面可能返回RANDOM模式
   * @note 模式可能随时间动态变化
   */
  AccessPattern GetAccessPattern(int32_t page_id) const;

private:
  /**
   * @brief 页面访问历史 - 访问模式分析的数据基础
   *
   * WHY层 - 设计意图：
   *   访问历史记录是模式识别和预测的基础数据结构。
   *   通过维护每个页面的访问时间序列，实现精准的访问模式分析。
   *
   * WHAT层 - 数据结构：
   *   - 外层映射：页面ID到时间戳列表
   *   - 时间戳列表：该页面的访问历史记录
   *   - 自动清理：定期清理过期历史记录
   *
   * HOW层 - 内存管理：
   *   - 容量限制：防止历史记录无限增长
   *   - 时间窗口：只保留最近一段时间的历史
   *   - 压缩存储：优化历史数据的存储格式
   *   - 并发安全：使用读写锁保护并发访问
   */
  std::unordered_map<int32_t, std::vector<std::chrono::steady_clock::time_point>> access_history_;

  /**
   * @brief 访问历史互斥锁 - 保护访问历史记录的并发访问
   */
  mutable std::mutex access_history_mutex_;

  /**
   * @brief 预取队列 - 待处理的预取任务队列
   *
   * WHY层 - 设计意图：
   *   预取队列实现生产者-消费者模式，解耦预取请求的提交和处理。
   *   通过队列缓冲，可以平滑预取请求的突发流量。
   *
   * WHAT层 - 队列内容：
   *   待预取的页面ID列表，按优先级排序。
   *   支持批量预取和优先级调度。
   *
   * HOW层 - 队列管理：
   *   - 优先级队列：高优先级页面优先预取
   *   - 容量控制：防止队列过大占用内存
   *   - 去重机制：避免重复预取同一页面
   *   - 超时处理：过期预取请求自动清理
   */
  std::vector<int32_t> prefetch_queue_;

  /**
   * @brief 预取队列互斥锁 - 保护预取队列的并发访问
   */
  mutable std::mutex prefetch_queue_mutex_;

  /**
   * @brief 预取工作线程 - 后台处理预取任务
   */
  std::thread prefetch_thread_;

  /**
   * @brief 停止预取标志 - 控制工作线程的运行状态
   */
  std::atomic<bool> stop_prefetch_;

  /**
   * @brief 预取启用标志 - 控制预取功能的开关
   */
  std::atomic<bool> enabled_;

  /**
   * @brief 统计信息 - 预取性能的量化指标
   */
  mutable std::atomic<PrefetcherStats> stats_;

  /**
   * @brief 最大预取大小 - 单次预取操作的上限
   */
  const size_t max_prefetch_size_;

  /**
   * @brief 预取工作线程函数 - 后台预取任务处理循环
   *
   * WHY层 - 设计意图：
   *   工作线程函数是预取器的核心执行逻辑，独立处理预取任务。
   *   通过独立线程，避免预取操作阻塞主事务处理。
   *
   * WHAT层 - 线程职责：
   *   - 监听预取队列的新任务
   *   - 执行页面预取操作
   *   - 更新统计信息
   *   - 处理异常情况
   *
   * HOW层 - 执行循环：
   *   1. 检查停止标志，决定是否退出
   *   2. 从队列获取待预取的页面
   *   3. 执行实际的预取操作
   *   4. 处理预取结果和异常
   *   5. 更新统计信息
   *   6. 等待新的预取任务
   *
   * 异常处理：
   *   - I/O错误：记录错误，继续处理其他任务
   *   - 内存不足：暂停预取，等待内存释放
   *   - 队列为空：进入低功耗等待状态
   *   - 系统负载高：降低预取频率
   *
   * 性能优化：
   *   - 批量处理：一次处理多个预取任务
   *   - 自适应频率：根据系统负载调整处理速度
   *   - 资源控制：限制CPU和内存资源的使用
   */
  void PrefetchWorker();
};

