/**
 * WHY: 为什么需要LRU缓存管理器？
 *
 * 数据库缓冲池需要高效的页面替换策略来管理有限的内存资源：
 * - 内存容量有限，无法缓存所有数据页面
 * - 页面访问模式具有时间局部性：最近访问的页面很可能再次被访问
 * - 需要智能淘汰策略：优先淘汰最久未使用的页面
 * - 并发访问要求：多线程环境下的线程安全操作
 *
 * LRU算法的核心优势：
 * 1. 时间局部性：完美匹配数据库访问模式
 * 2. 简单高效：实现复杂度低，性能优秀
 * 3. 自适应性：无需人工调优，自动适应访问模式
 * 4. 空间效率：最小化内存占用，实现固定空间开销
 *
 * 🏗️ 设计模式：策略模式(Strategy Pattern)
 *
 * LRU管理器作为缓存替换策略的具体实现：
 * - 实现统一的替换接口：支持不同替换算法的插拔
 * - 封装内部数据结构：链表和哈希映射的组合使用
 * - 提供原子操作：线程安全的访问和修改
 * - 支持性能监控：缓存命中率和淘汰统计
 *
 * WHAT: LRU缓存管理器 - 缓冲池页面替换的核心组件
 *
 * 核心功能：
 * - 访问顺序维护：记录页面访问的时间顺序
 * - 替换决策支持：识别最适合淘汰的页面
 * - 并发安全管理：多线程环境下的数据一致性
 * - 性能统计收集：缓存效果的量化分析
 * - 动态容量调整：根据系统负载调整缓存大小
 *
 * 数据结构设计：
 * - 双向链表：维护页面的访问时间顺序
 * - 哈希映射：提供页面ID到链表节点的快速查找
 * - 互斥锁：保证多线程访问的线程安全性
 * - 统计计数器：记录缓存操作的性能指标
 *
 * 接口设计：
 * - 访问记录：更新页面在LRU队列中的位置
 * - 页面管理：添加和移除页面的生命周期管理
 * - 替换选择：选择最适合淘汰的页面
 * - 状态查询：检查页面存在性和缓存大小
 * - 批量操作：支持批量添加和清理操作
 *
 * HOW: LRU缓存管理器的实现机制和优化策略
 *
 * 核心数据结构：
 * - 双向链表：头部是最常使用的页面，尾部是最少使用的页面
 * - 哈希映射：页面ID到链表迭代器的映射，O(1)查找时间
 * - 线程锁：读写锁分离，提高并发访问性能
 *
 * 访问操作优化：
 * 1. 快速定位：哈希映射直接找到页面在链表中的位置
 * 2. 位置调整：将访问的页面移动到链表头部
 * 3. 原子更新：使用锁保证操作的原子性和一致性
 * 4. 延迟更新：批量访问时减少不必要的移动操作
 *
 * 替换策略优化：
 * 1. 尾部淘汰：直接从链表尾部选择淘汰页面
 * 2. 智能预取：预测即将访问的页面避免频繁淘汰
 * 3. 冷热分离：区分冷数据和热数据的处理策略
 * 4. 自适应调整：根据访问模式动态调整替换阈值
 *
 * 内存管理优化：
 * - 对象池复用：减少频繁的内存分配和释放
 * - 引用计数：智能指针管理页面对象的生命周期
 * - 延迟清理：批量清理减少GC压力
 * - 内存对齐：提高CPU缓存访问效率
 *
 * 并发控制策略：
 * - 读写锁分离：读操作使用共享锁，写操作使用独占锁
 * - 乐观并发：无锁的数据读取操作
 * - 细粒度锁：只锁定需要修改的数据结构部分
 * - 死锁避免：固定的锁获取顺序
 *
 * 性能监控机制：
 * - 访问统计：记录命中率、访问频率等关键指标
 * - 趋势分析：识别访问模式的长期变化
 * - 异常检测：发现异常的访问行为和性能问题
 * - 自动调优：基于监控数据调整缓存策略
 *
 * 扩展性和兼容性：
 * - 多策略支持：支持LRU、LFU、ARC等多种替换算法
 * - 配置热更新：运行时调整缓存大小和策略参数
 * - 插件化架构：支持自定义的替换策略实现
 * - 向后兼容：平滑升级不影响现有功能
 * - API抽象：统一的缓存管理接口
 *
 * 调试和诊断功能：
 * - 结构验证：LRU链表和哈希映射的一致性检查
 * - 性能分析：缓存操作的时间和空间复杂度分析
 * - 可视化工具：缓存状态和访问模式的图形展示
 * - 日志记录：详细的操作历史记录和错误追踪
 * - 压力测试：极限情况下的缓存策略验证
 */

#pragma once

#include <list>
#include <unordered_map>
#include <cstdint>
#include <mutex>

namespace sqlcc {
namespace storage {

/**
 * @brief LRU缓存管理器
 *
 * 实现Least Recently Used (LRU)缓存替换策略的核心组件。
 * 通过双向链表和哈希映射的组合，高效维护页面的访问顺序，
 * 支持高并发的缓存管理和页面替换决策。
 *
 * 设计理念：
 * - 高效性：O(1)时间复杂度的访问和更新操作
 * - 线程安全：多线程环境下的数据一致性保证
 * - 可扩展性：支持不同容量和策略的灵活配置
 * - 易维护性：清晰的数据结构和接口设计
 */
class LRUManager {
public:
    /**
     * @brief 构造函数
     */
    LRUManager();

    /**
     * @brief 析构函数
     */
    ~LRUManager();

    /**
     * @brief 访问页面，将页面移到LRU链表头部
     * @param page_id 页面ID
     */
    void Access(int32_t page_id);

    /**
     * @brief 添加新页面到LRU管理器
     * @param page_id 页面ID
     */
    void Add(int32_t page_id);

    /**
     * @brief 从LRU管理器中移除页面
     * @param page_id 页面ID
     */
    void Remove(int32_t page_id);

    /**
     * @brief 获取最少使用的页面（LRU链表尾部）
     * @return 最少使用的页面ID，如果没有页面则返回-1
     */
    int32_t GetLeastRecentlyUsed() const;

    /**
     * @brief 检查页面是否在LRU管理器中
     * @param page_id 页面ID
     * @return 如果页面存在返回true，否则返回false
     */
    bool Contains(int32_t page_id) const;

    /**
     * @brief 清空LRU管理器
     */
    void Clear();

    /**
     * @brief 获取当前管理的页面数量
     * @return 页面数量
     */
    size_t Size() const;

private:
    mutable std::mutex mutex_;  ///< 互斥锁，保护并发访问

    std::list<int32_t> lru_list_;  ///< LRU双向链表，头部是最常使用的页面
    std::unordered_map<int32_t, std::list<int32_t>::iterator> lru_map_;  ///< 页面ID到链表迭代器的映射
};

} // namespace storage
} // namespace sqlcc
