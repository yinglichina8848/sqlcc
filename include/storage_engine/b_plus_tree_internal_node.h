#pragma once

#include "storage_engine/b_plus_tree_node.h"
#include <memory>
#include <string>
#include <vector>

namespace sqlcc {

/**
 * WHY: 为什么需要B+树内部节点？
 *
 * B+树索引系统需要专门的内部节点来构建树形结构：
 * - 内部节点存储索引键和子节点指针，建立多层索引
 * - 内部节点不存储数据，只存储路由信息，减少内存占用
 * - 内部节点的多路分支特性决定了B+树的扇出和深度
 * - 内部节点的分裂和合并操作决定了树结构的动态平衡
 *
 * 内部节点的核心价值：
 * 1. 索引路由：提供从根到叶子的快速路径查找
 * 2. 空间效率：只存储键值和指针，不存储实际数据
 * 3. 平衡维护：通过分裂合并保持树的平衡性
 * 4. 查询优化：减少磁盘访问次数，提高查询性能
 *
 * 🏗️ 设计模式：组合模式(Composite Pattern)
 *
 * 内部节点作为树结构的一部分：
 * - 继承节点基类：统一接口和基础功能
 * - 实现索引特化：键值存储和子节点管理
 * - 参与树操作：分裂合并的内部节点逻辑
 * - 支持递归遍历：树形结构的深度优先访问
 *
 * 内部节点特化的设计考虑：
 * - 键值有序：维护分隔键的有序性和唯一性
 * - 指针管理：子节点指针的生命周期管理
 * - 分裂策略：键值分配和子节点重组的策略
 * - 合并条件：相邻节点合并的条件判断
 *
 * WHAT: B+树内部节点 - 索引路由的核心组件
 *
 * 核心功能：
 * - 键值索引管理：存储分隔键值，建立搜索路径
 * - 子节点指针维护：管理子节点的页面引用
 * - 路由查找操作：根据键值确定子节点方向
 * - 分裂合并处理：节点大小的动态调整
 * - 树结构平衡：维护B+树的平衡特性
 *
 * 数据结构设计：
 * - 键值数组：有序存储的分隔键值集合
 * - 子节点指针：指向子节点的页面ID数组
 * - 键值映射：每个键值对应左右子节点的范围
 * - 页面绑定：与磁盘页面的直接映射
 * - 元数据管理：节点状态和边界信息
 *
 * 接口设计：
 * - 子节点管理：InsertChild/RemoveChild操作
 * - 路由查找：FindChildPageId确定搜索方向
 * - 结构调整：Split/Merge处理节点重组
 * - 状态查询：键值和指针的访问接口
 * - 调试支持：内部状态的检查方法
 *
 * HOW: B+树内部节点的实现机制和优化策略
 *
 * 数据组织架构：
 * - 键值排序：严格有序的分隔键值数组
 * - 指针对应：键值左右的子节点指针关联
 * - 范围划分：每个子节点负责的键值范围
 * - 边界处理：最小值和最大值的特殊处理
 *
 * 查找算法优化：
 * 1. 二分搜索：O(log n)的键值定位效率
 * 2. 范围判断：确定目标键值所属的子节点
 * 3. 指针返回：直接返回目标子节点的页面ID
 * 4. 缓存加速：热点键值的查找结果缓存
 *
 * 插入算法优化：
 * 1. 查找位置：确定新键值和子指针的插入点
 * 2. 数组调整：有序数组的插入操作维护排序
 * 3. 指针关联：建立键值与子节点的正确关联
 * 4. 分裂检查：节点满载时的分裂触发条件
 * 5. 递归传播：向上层传播插入导致的分裂
 *
 * 删除算法优化：
 * 1. 查找定位：快速找到要删除的键值位置
 * 2. 数组重组：有序数组的删除操作
 * 3. 指针调整：子节点指针的重新关联
 * 4. 合并检查：节点过少时的合并触发条件
 * 5. 递归收缩：向下层传播删除导致的合并
 *
 * 分裂策略优化：
 * - 中间键值选择：选择合适的键值作为分隔点
 * - 子节点分配：左右子节点的均衡分配
 * - 键值重分布：分裂后键值的重新组织
 * - 父节点更新：向上传播新的索引信息
 * - 空间预留：为未来操作预留空间
 *
 * 合并策略优化：
 * - 兄弟节点选择：选择合适的相邻节点进行合并
 * - 键值重排序：合并后键值的有序重组
 * - 指针重关联：子节点指针的重新建立
 * - 父节点调整：向上层删除合并的索引信息
 * - 空间回收：释放不需要的节点空间
 *
 * 内存管理优化：
 * - 数组预分配：减少动态扩容的开销
 * - 引用计数：智能指针管理子节点引用
 * - 延迟加载：按需加载子节点信息
 * - 缓存策略：节点数据的内存缓存
 * - 垃圾回收：不再使用的节点清理
 *
 * 并发控制策略：
 * - 读写锁分离：读操作共享锁，写操作独占锁
 * - 乐观并发：版本控制的无锁读取
 * - 细粒度锁：只锁定操作涉及的键值范围
 * - 死锁避免：固定的节点访问顺序
 * - MVCC支持：多版本并发控制
 *
 * 磁盘I/O优化：
 * - 页面对齐：磁盘访问的页面边界对齐
 * - 预写日志：WAL保证数据一致性
 * - 异步刷盘：后台的页面写入操作
 * - 批量提交：减少磁盘同步次数
 * - RAID友好：适合RAID的I/O模式
 *
 * 故障恢复机制：
 * - WAL重放：崩溃后通过日志恢复索引
 * - 一致性检查：启动时的内部节点验证
 * - 自动修复：检测并修复损坏的索引数据
 * - 备份恢复：冷热备份的数据保护
 * - 版本控制：多版本数据的故障回退
 *
 * 性能监控和调优：
 * - 访问统计：查找频率和命中率的监控
 * - 空间利用率：键值存储效率的分析
 * - 分裂合并频率：结构调整成本的评估
 * - 缓存效果：内存缓存的命中率分析
 * - I/O性能：磁盘访问模式的优化建议
 *
 * 扩展性和兼容性：
 * - 多键支持：复合键值的索引支持
 * - 动态调整：运行时参数的动态调整
 * - 插件架构：可扩展的索引实现
 * - 向后兼容：旧版本数据的平滑迁移
 * - API抽象：统一的内部节点操作接口
 *
 * 调试和诊断：
 * - 结构验证：键值有序性和指针正确性检查
 * - 一致性测试：父子节点关系的验证
 * - 性能分析：查找路径和访问深度的分析
 * - 内存分析：节点内存使用的详细统计
 * - 日志记录：操作历史的详细记录
 */
class BPlusTreeInternalNode : public BPlusTreeNode {
public:
    /**
     * @brief 构造函数
     * @param storage_engine 存储引擎指针，用于磁盘操作
     * @param page_id 内部节点对应的磁盘页面ID
     * @param is_new 是否为新建节点，用于初始化逻辑
     */
    BPlusTreeInternalNode(std::shared_ptr<StorageEngine> storage_engine, int32_t page_id, bool is_new = false);

    /**
     * @brief 析构函数
     * @details 释放内部节点占用的资源，清理子节点引用
     */
    ~BPlusTreeInternalNode() override;

    // 实现基类纯虚函数
    void SerializeToPage() override;
    void DeserializeFromPage() override;
    void Clear() override;
    bool IsFull() const override;

    // 内部节点特有的子节点管理方法
    void InsertChild(int32_t child_page_id);
    void InsertChild(int32_t child_page_id, const std::string& key);
    void RemoveChild(int32_t child_page_id);
    int32_t FindChildPageId(const std::string& key) const;

    // 分裂和合并操作（内部节点特化）
    void Split(std::unique_ptr<BPlusTreeInternalNode>& new_node);
    void Merge(std::unique_ptr<BPlusTreeInternalNode> right_node, const std::string& parent_key);

    // 调试和测试辅助方法
    const std::vector<std::string>& GetKeys() const { return keys_; }
    const std::vector<int32_t>& GetChildPageIds() const { return child_page_ids_; }

private:
    std::vector<std::string> keys_;           /**< 有序存储的分隔键值数组 */
    std::vector<int32_t> child_page_ids_;     /**< 子节点页面ID数组，数量比键值多1 */
};

} // namespace sqlcc
