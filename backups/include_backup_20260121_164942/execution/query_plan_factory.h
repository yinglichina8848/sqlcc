/**
 * WHY: 为什么需要专门的查询计划工厂系统？
 *
 * 数据库系统需要将SQL语句转换为高效的执行计划，传统方案存在诸多问题：
 * - 语句类型判断复杂：不同SQL语句需要不同执行策略
 * - 对象创建耦合严重：执行器直接依赖具体查询计划类
 * - 扩展性差：新增语句类型需要修改所有相关工厂代码
 * - 资源管理混乱：查询计划对象的生命周期难以控制
 * - 优化策略单一：缺乏针对不同查询的个性化优化
 *
 * 查询计划工厂系统的核心价值：
 * 1. 统一创建接口：提供一致的查询计划创建入口
 * 2. 类型安全保证：编译时确保语句类型与计划类型的匹配
 * 3. 资源管理优化：智能管理查询计划对象的生命周期
 * 4. 扩展灵活性：支持动态添加新的查询计划类型
 * 5. 性能优化集成：内置查询优化策略的选择机制
 *
 * 🏗️ 设计模式：工厂方法模式(Factory Method Pattern) + 抽象工厂模式(Abstract Factory Pattern)
 *
 * 查询计划工厂作为工厂方法模式的经典应用：
 * - 产品族抽象：统一查询计划接口，屏蔽具体实现差异
 * - 创建逻辑封装：将复杂的对象创建逻辑封装在工厂内部
 * - 依赖倒置：高层模块依赖抽象查询计划而非具体实现
 * - 开闭原则：新增查询计划类型无需修改现有工厂代码
 * - 单一职责：工厂专注于对象创建，不涉及执行逻辑
 *
 * SOLID原则体现：
 * - 单一职责：查询计划工厂专门负责查询计划的创建和管理
 * - 开闭原则：新查询类型通过扩展工厂实现
 * - 里氏替换：具体查询计划可以替换抽象查询计划
 * - 接口隔离：工厂接口精确定义创建方法
 * - 依赖倒置：工厂依赖查询计划抽象而非具体实现
 *
 * WHAT: 查询计划工厂系统 - 数据库查询执行计划生成框架
 *
 * 核心功能：
 * - 语句类型识别：自动识别SQL语句的类型和结构特征
 * - 计划对象创建：根据语句类型创建相应的查询计划对象
 * - 优化策略选择：为不同查询选择合适的优化策略
 * - 资源分配管理：管理查询执行所需的系统资源
 * - 执行上下文准备：为查询执行准备必要的上下文信息
 *
 * 系统组件：
 * - QueryPlanFactory：核心工厂类，负责查询计划的创建
 * - UnifiedQueryPlan：统一的查询计划接口，定义执行契约
 * - StatementAnalyzer：语句分析器，识别语句类型和特征
 * - OptimizationSelector：优化选择器，选择合适的优化策略
 * - ResourceAllocator：资源分配器，管理查询执行资源
 * - ContextBuilder：上下文构建器，准备执行上下文
 *
 * 查询计划类型：
 * - SelectPlan：SELECT查询计划，支持各种查询操作
 * - InsertPlan：INSERT插入计划，支持批量插入优化
 * - UpdatePlan：UPDATE更新计划，支持条件更新
 * - DeletePlan：DELETE删除计划，支持级联删除
 * - DDLPlan：数据定义语言计划，支持表结构操作
 * - TransactionPlan：事务管理计划，支持ACID属性
 * - SystemPlan：系统维护计划，支持数据库管理操作
 * - CustomPlan：自定义查询计划，支持扩展功能
 *
 * 工厂创建策略：
 * - 静态工厂方法：使用静态方法提供全局创建入口
 * - 延迟初始化：按需创建查询计划对象
 * - 对象池复用：复用常用的查询计划对象
 * - 缓存机制：缓存频繁使用的查询计划模板
 * - 并发安全：支持多线程并发创建查询计划
 *
 * 接口设计：
 * - 创建接口：createPlan提供统一的计划创建方法
 * - 配置接口：支持工厂行为的配置和定制
 * - 监控接口：提供工厂性能和使用情况的监控
 * - 扩展接口：支持第三方查询计划的注册和集成
 * - 调试接口：提供查询计划创建过程的调试信息
 *
 * HOW: 查询计划工厂系统的实现机制
 *
 * 计划创建流程：
 * 1. 语句分析：解析SQL语句AST，提取关键信息
 * 2. 类型识别：根据语句特征确定查询计划类型
 * 3. 优化选择：评估查询复杂度，选择优化策略
 * 4. 资源评估：计算查询执行所需的系统资源
 * 5. 计划构建：组装查询计划的各个执行组件
 * 6. 上下文准备：设置查询执行的上下文环境
 * 7. 验证检查：验证查询计划的正确性和完整性
 *
 * 类型识别实现：
 * 1. 语法树遍历：遍历SQL语句AST提取关键节点
 * 2. 模式匹配：使用模式匹配识别语句类型和结构
 * 3. 语义分析：分析语句语义确定执行策略
 * 4. 规则引擎：基于规则的语句分类和处理
 * 5. 机器学习：使用ML模型进行语句类型预测
 *
 * 优化策略实现：
 * 1. 代价估算：基于统计信息估算不同执行计划的代价
 * 2. 启发式规则：应用数据库优化的经典启发式规则
 * 3. 动态规划：对复杂查询使用动态规划算法
 * 4. 遗传算法：使用遗传算法搜索最优执行计划
 * 5. 学习优化：基于历史执行数据进行优化
 *
 * 资源管理实现：
 * 1. 内存预算：为查询执行分配合理的内存预算
 * 2. CPU调度：控制查询执行的CPU资源使用
 * 3. I/O调度：优化磁盘I/O操作的调度策略
 * 4. 并发控制：管理查询执行的并发度和并行度
 * 5. 超时控制：防止查询执行时间过长的保护机制
 *
 * 对象生命周期实现：
 * 1. 智能指针：使用智能指针管理查询计划对象的生命周期
 * 2. 引用计数：基于引用计数的对象共享和回收
 * 3. 池化管理：对象池技术复用查询计划对象
 * 4. 延迟销毁：异步销毁不再使用的查询计划对象
 * 5. 内存监控：实时监控查询计划对象的内存使用
 *
 * 并发安全实现：
 * 1. 线程安全：确保工厂方法在多线程环境下的安全使用
 * 2. 锁优化：使用细粒度锁最小化锁竞争
 * 3. 无锁算法：对热点路径使用无锁数据结构
 * 4. 原子操作：使用原子操作保证状态一致性
 * 5. 内存屏障：保证多线程环境下的内存可见性
 *
 * 性能优化策略：
 * - 缓存优化：缓存常用的查询计划模板和模式
 * - 预编译：预编译频繁使用的查询模式
 * - 并行创建：并行创建复杂的查询计划组件
 * - SIMD加速：使用向量化指令加速模式匹配
 * - GPU加速：利用GPU加速复杂查询的计划生成
 *
 * 错误处理实现：
 * 1. 类型错误：处理无法识别的语句类型的错误
 * 2. 资源错误：处理资源不足无法创建计划的错误
 * 3. 配置错误：处理工厂配置错误的异常情况
 * 4. 依赖错误：处理依赖组件缺失的错误
 * 5. 超时错误：处理计划创建超时的错误情况
 *
 * 扩展性设计：
 * - 插件架构：支持第三方查询计划的动态加载
 * - 配置驱动：基于配置文件的工厂行为定制
 * - 服务化：将工厂功能服务化，支持分布式调用
 * - AI增强：集成AI技术进行智能计划生成
 * - 云原生：适配云环境的多租户和弹性伸缩
 *
 * 调试和诊断：
 * - 创建跟踪：详细记录查询计划的创建过程
 * - 性能分析：分析计划生成过程中的性能瓶颈
 * - 类型调试：调试语句类型识别的准确性
 * - 资源调试：调试资源分配和使用的合理性
 * - 可视化工具：可视化查询计划的创建和优化过程
 */

#ifndef SQLCC_EXECUTION_QUERY_PLAN_FACTORY_H
#define SQLCC_EXECUTION_QUERY_PLAN_FACTORY_H

#include <memory>
#include <string>
#include <unordered_map>

namespace sqlcc {

class DatabaseManager;
class UserManager;
class SystemDatabase;
class UnifiedQueryPlan;

namespace sql_parser {
class Statement;
} // namespace sql_parser

/**
 * @brief 查询计划工厂 - 负责创建各种查询计划
 *
 * 根据SQL语句类型创建相应的查询计划对象
 */
class QueryPlanFactory {
public:
    /**
     * @brief 创建查询计划
     * @param stmt SQL语句AST
     * @param db_manager 数据库管理器
     * @param user_manager 用户管理器
     * @param system_db 系统数据库
     * @return 查询计划对象
     */
    static std::unique_ptr<UnifiedQueryPlan> createPlan(
        std::unique_ptr<sql_parser::Statement> stmt,
        std::shared_ptr<DatabaseManager> db_manager,
        std::shared_ptr<UserManager> user_manager,
        std::shared_ptr<SystemDatabase> system_db);
};

} // namespace sqlcc

#endif // SQLCC_EXECUTION_QUERY_PLAN_FACTORY_H
